// Records a prototype at 390×844: intro, the four fields, Envoyer, success. Writes a video and key frames.
import { createRequire } from "node:module";
import { mkdirSync, renameSync } from "node:fs";
const require = createRequire(process.env.HOME + "/.cache/madrasati-qa/package.json");
const { chromium } = require("playwright-core");
const [url, out, tag = "v"] = process.argv.slice(2);
mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.HOME + "/Library/Caches/ms-playwright/chromium-1248/chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing", args: ["--use-angle=metal", "--enable-gpu", "--ignore-gpu-blocklist"] });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, recordVideo: { dir: out, size: { width: 780, height: 1688 } } });
const page = await ctx.newPage();
const errors = []; page.on("pageerror", (e) => errors.push(String(e))); page.on("console", (m) => m.type() === "error" && errors.push(m.text()));
const t0 = Date.now(); const stamp = () => ((Date.now() - t0) / 1000).toFixed(1);
await page.goto(url, { waitUntil: "load" });
await page.evaluate(() => document.fonts.ready);
const shot = (n) => page.screenshot({ path: `${out}/${tag}-${n}.png` });
await page.waitForTimeout(2600); await shot("1-intro-end");
const type = async (sel, text) => { await page.locator(sel).click(); await page.locator(sel).pressSequentially(text, { delay: 110 }); await page.keyboard.press("Tab"); await page.waitForTimeout(650); };
await type("#prenom", "Amine");
await type("#nom", "Ben Salah");
await page.locator("#date").fill("2026-11-14"); await page.locator("#date").dispatchEvent("change"); await page.waitForTimeout(900);
await shot("2-filling");
await page.locator("#heure").fill("14:30"); await page.locator("#heure").dispatchEvent("change"); await page.waitForTimeout(1100);
await shot("3-ready");
await page.locator(process.env.SUBMIT || "#envoyer").click();
await page.waitForTimeout(1300); await shot("4-success-moment");
await page.waitForTimeout(3600); await shot("5-success-end");
const video = page.video(); await ctx.close(); await browser.close();
const p = await video.path(); renameSync(p, `${out}/${tag}.webm`);
console.log("done", stamp(), errors.length ? "ERRORS " + errors.join(" | ") : "no errors");
